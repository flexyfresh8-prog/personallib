#!/usr/bin/env python3
"""
LiquidGlass bundler + syntax validator.

- Collects every .luau module under src/LiquidGlass/
- Rewrites Roblox-style requires  require(script.Parent.Core.Util)
  into string-keyed requires inside a single self-contained file
- Emits build/LiquidGlass.lua  (paste into a ModuleScript, or loadstring it)
- Validates Lua syntax of every module and the final bundle via luaparser

Usage:
  python3 tools/build.py            # build + validate
  python3 tools/build.py --check    # validate only
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src", "LiquidGlass")
OUT = os.path.join(ROOT, "build", "LiquidGlass.lua")

HEADER_RE = re.compile(r"^--@module[ \t]+([A-Za-z0-9_/\.\-]+)[ \t]*$", re.M)
REQUIRE_RE = re.compile(r"require\(\s*(script(?:\.[A-Za-z_][A-Za-z0-9_]*)*)\s*\)")


def module_key(relpath: str) -> str:
    rel = relpath.replace("\\", "/")
    if rel == "init.luau" or rel.endswith("/init.luau"):
        rel = rel[: -len("init.luau")]
    elif rel.endswith(".luau"):
        rel = rel[: -len(".luau")]
    return ("LiquidGlass/" + rel.strip("/")).rstrip("/")


def collect():
    modules = {}
    for dirpath, _dirnames, filenames in os.walk(SRC):
        for fn in sorted(filenames):
            if not fn.endswith(".luau"):
                continue
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, SRC)
            with open(full, "r", encoding="utf-8") as f:
                body = f.read()
            m = HEADER_RE.search(body)
            if not m:
                raise SystemExit(f"[build] missing --@module header: {rel}")
            declared = m.group(1)
            key = module_key(rel)
            if declared != key:
                raise SystemExit(f"[build] header mismatch in {rel}: declared {declared}, expected {key}")
            modules[key] = body
    return modules


def resolve_require(cur_key: str, expr: str) -> str:
    segs = expr[len("script"):].split(".")
    parts = cur_key.split("/")
    for seg in segs:
        if not seg:
            continue
        if seg == "Parent":
            if len(parts) <= 1:
                raise SystemExit(f"[build] require walks above root from {cur_key}: {expr}")
            parts.pop()
        else:
            parts.append(seg)
    return "/".join(parts)


def rewrite(cur_key: str, body: str) -> str:
    def repl(match):
        key = resolve_require(cur_key, match.group(1))
        return f'require("{key}")'
    return REQUIRE_RE.sub(repl, body)


def bundle(modules) -> str:
    # validate require graph first
    for key, body in modules.items():
        stripped = HEADER_RE.sub("", body, count=1)
        for match in REQUIRE_RE.finditer(stripped):
            target = resolve_require(key, match.group(1))
            if target not in modules:
                raise SystemExit(f"[build] {key} requires missing module: {target}")
        # any stray 'script' usage outside requires?
        leftovers = re.findall(r"\bscript\b", REQUIRE_RE.sub("", stripped))
        if leftovers:
            raise SystemExit(f"[build] {key} uses bare `script` outside require() ({len(leftovers)}x)")

    parts = []
    parts.append("--[[")
    parts.append("    LiquidGlass UI - bundled single-file build (generated by tools/build.py)")
    parts.append("    Do not edit by hand - edit src/ and rebuild.")
    parts.append("")
    parts.append("    Use:")
    parts.append("      loadstring(game:HttpGet(\"<raw url>\"))()   -- executor")
    parts.append("      local LiquidGlass = require(script.Parent.LiquidGlass)  -- Studio ModuleScript")
    parts.append("]]")
    parts.append("")
    parts.append("local __defs, __cache = {}, {}")
    parts.append("local function require(key)")
    parts.append("\tlocal cached = __cache[key]")
    parts.append("\tif cached ~= nil then")
    parts.append("\t\treturn cached")
    parts.append("\tend")
    parts.append("\tlocal def = __defs[key]")
    parts.append("\tif def == nil then")
    parts.append("\t\terror(\"[LiquidGlass] module not found: \" .. tostring(key), 2)")
    parts.append("\tend")
    parts.append("\tcached = def()")
    parts.append("\t__cache[key] = cached")
    parts.append("\treturn cached")
    parts.append("end")
    parts.append("")

    # deterministic order: core first, entry last
    ordered = sorted(modules.keys(), key=lambda k: (k.count("/") == 0, k))
    for key in ordered:
        body = HEADER_RE.sub("", modules[key], count=1).strip("\n")
        body = rewrite(key, body)
        parts.append(f'__defs["{key}"] = function()')
        parts.append(body)
        parts.append("end")
        parts.append("")

    parts.append('return require("LiquidGlass")')
    parts.append("")
    return "\n".join(parts)


def validate_lua(path: str, source: str) -> bool:
    try:
        from luaparser import ast
    except ImportError:
        print("[check] luaparser not installed; skipping syntax validation")
        return True
    try:
        ast.parse(source)
        return True
    except Exception as e:
        print(f"[check] SYNTAX ERROR in {path}: {e}")
        return False


def main():
    check_only = "--check" in sys.argv
    modules = collect()
    print(f"[build] collected {len(modules)} modules:")
    for key in sorted(modules):
        print(f"        {key}")

    ok = True
    for key, body in modules.items():
        ok = validate_lua(key, body) and ok
    if not ok:
        sys.exit(1)

    if check_only:
        # also validate demo
        demo = os.path.join(ROOT, "src", "Demo", "DemoClient.client.luau")
        if os.path.exists(demo):
            with open(demo, "r", encoding="utf-8") as f:
                ok = validate_lua("Demo/DemoClient.client.luau", f.read())
        sys.exit(0 if ok else 1)

    bundled = bundle(modules)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(bundled)
    lines = bundled.count("\n")
    print(f"[build] wrote {OUT} ({lines} lines, {len(bundled)} bytes)")

    ok = validate_lua("build/LiquidGlass.lua", bundled)
    demo = os.path.join(ROOT, "src", "Demo", "DemoClient.client.luau")
    if os.path.exists(demo):
        with open(demo, "r", encoding="utf-8") as f:
            ok = validate_lua("Demo/DemoClient.client.luau", f.read()) and ok
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
