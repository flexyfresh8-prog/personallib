                        or input.UserInputType == Enum.UserInputType.Touch) then
                        dragging = false
                        Animator.Spring(thumbScale, "Scale", 1, Config.Spring.Snappy)
                end
        end))

        local thumbScale = Util.New("UIScale", { Scale = 1, Parent = thumb })
        apply(value, false)

        local control = {
                Kind = "Slider",
                Frame = card.Frame,
                Changed = changed,
                Get = function()
                        return value
                end,
                Set = function(_, newValue, silent)
                        apply(newValue or min, false)
                        if not silent then
                                changed:Fire(value)
                        end
                end,
                SetRange = function(_, newMin, newMax)
                        min = newMin
                        max = newMax
                        apply(value, false)
                end,
                Destroy = function()
                        card:Destroy()
                end,
        }
        tab._Controls[cfg.Name or "Slider"] = control
        return control
end

