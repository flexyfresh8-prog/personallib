		Parent = toast,
	})
	Util.Corner(circle, 15)
	Util.Stroke(circle, ctxColor(variantKey), 0.45, 1)
	Elements.VectorIcon({ Color = ctxColor, Tint = function() end }, iconKind, circle, 15, variantKey, 2.2)

