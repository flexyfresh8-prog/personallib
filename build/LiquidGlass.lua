local __defs, __cache = {}, {}
local function require(key)
	local cached = __cache[key]
	if cached ~= nil then
		return cached
	end
	local def = __defs[key]
	if def == nil then
		error("[LiquidGlass] module not found: " .. tostring(key), 2)
	end
	cached = def()
	__cache[key] = cached
	return cached
end

